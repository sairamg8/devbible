const show = (src) => { try { console.log(`  ${src.padEnd(28)} = ${JSON.stringify(eval(src))}`); } catch(e){ console.log(`  ${src.padEnd(28)} -> ${e.constructor.name}`); } };
console.log('--- the ones that bite ---');
show('2 ** 3 ** 2');
show('(2 ** 3) ** 2');
show('1 + 2 + "3"');
show('"1" + 2 + 3');
show('true ? 1 : true ? 2 : 3');
show('typeof 1 + 1');
show('typeof (1 + 1)');
show('!true === false');
show('1 < 2 < 3');
show('3 > 2 > 1');
console.log('\n--- typeof vs instanceof precedence ---');
show('typeof [] === "object"');
console.log('\n--- comma operator has the LOWEST precedence ---');
show('(1, 2, 3)');
let x; x = (1, 2, 3); console.log('  x = (1,2,3)                  =', x);
console.log('\n--- assignment is right-associative and returns a value ---');
let a, b; a = b = 5; console.log('  a = b = 5  -> a =', a, 'b =', b);
console.log('\n--- && binds tighter than || ---');
show('true || false && false');
show('(true || false) && false');
