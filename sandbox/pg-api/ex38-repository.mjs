// Phase 9 pages 01, 06, 07 — the repository module: what a repo function takes,
// what the driver hands back, and the SQLSTATE→HTTP mapping produced for real.
import pg from 'pg';

const URL = 'postgres://devbible:devbible@127.0.0.1:55432/devbible';
const pool = new pg.Pool({connectionString: URL, max: 5});
const q = (...a) => pool.query(...a);
const line = (t) => console.log(`\n=== ${t} ===`);

await q(`DROP TABLE IF EXISTS r_orders, r_users CASCADE`);
await q(`CREATE TABLE r_users (
  id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  email      text NOT NULL UNIQUE,
  full_name  text NOT NULL,
  age        int CHECK (age >= 0),
  created_at timestamptz NOT NULL DEFAULT now())`);
await q(`CREATE TABLE r_orders (
  id      bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES r_users(id),
  total   numeric(10,2) NOT NULL)`);
await q(`INSERT INTO r_users (email, full_name, age)
         VALUES ('ada@x.com','Ada Lovelace',36)`);

// --- 1. the repository takes an executor, not a pool -----------------------
// Both pg.Pool and pg.Client expose .query(text, params) with the same result
// shape, so one function body serves both a standalone call and a transaction.
line('1. the same repo function against a Pool and against a Client');
{
  const findByEmail = (db, email) =>
    db.query(`SELECT id, email, full_name FROM r_users WHERE email = $1`, [email]);

  const viaPool = await findByEmail(pool, 'ada@x.com');
  const client = await pool.connect();
  let viaClient;
  try {
    viaClient = await findByEmail(client, 'ada@x.com');
  } finally {
    client.release();
  }
  console.log('via pool  :', viaPool.rows[0]);
  console.log('via client:', viaClient.rows[0]);
  console.log('same shape:', JSON.stringify(viaPool.rows) === JSON.stringify(viaClient.rows));
  console.log('constructor names:', pool.constructor.name, '/', client.constructor.name);
}

// --- 2. findById when the row is not there ---------------------------------
line('2. findById on a missing id — what the driver actually returns');
{
  const r = await q(`SELECT id, email FROM r_users WHERE id = $1`, [999999]);
  console.log('rowCount      :', r.rowCount);
  console.log('rows          :', JSON.stringify(r.rows));
  console.log('rows[0]       :', r.rows[0]);
  console.log('typeof rows[0]:', typeof r.rows[0]);
  console.log('rows[0] ?? null:', r.rows[0] ?? null);
  // The often-assumed "it throws" is wrong: a SELECT matching nothing is a
  // completely successful query that returns zero rows.
  console.log('did it throw? : no — zero rows is a success');
}

// --- 3. create: INSERT ... RETURNING, and the row → domain mapping ----------
line('3. create via INSERT ... RETURNING');
{
  const r = await q(
    `INSERT INTO r_users (email, full_name, age) VALUES ($1,$2,$3)
     RETURNING id, email, full_name, age, created_at`,
    ['grace@x.com', 'Grace Hopper', 45]);
  console.log('raw row  :', r.rows[0]);
  console.log('col types:', Object.fromEntries(
    Object.entries(r.rows[0]).map(([k, v]) =>
      [k, v === null ? 'null' : v.constructor.name])));
  const toDomain = (row) => ({
    id: String(row.id),               // bigint arrives as a string
    email: row.email,
    fullName: row.full_name,
    age: row.age,
    createdAt: row.created_at.toISOString(),
  });
  console.log('domain   :', toDomain(r.rows[0]));
}

// --- 4. every error a repository has to map, produced for real -------------
line('4. the SQLSTATE table, generated by actually causing each error');
{
  const cases = [
    ['duplicate email (UNIQUE)',
      `INSERT INTO r_users (email, full_name) VALUES ('ada@x.com','Dup')`, []],
    ['order for a user that does not exist (FK)',
      `INSERT INTO r_orders (user_id, total) VALUES (999999, 10)`, []],
    ['negative age (CHECK)',
      `INSERT INTO r_users (email, full_name, age) VALUES ('n@x.com','N',-1)`, []],
    ['missing full_name (NOT NULL)',
      `INSERT INTO r_users (email) VALUES ('m@x.com')`, []],
    ['id = "abc" (invalid text representation)',
      `SELECT * FROM r_users WHERE id = $1`, ['abc']],
    ['column that is not there (undefined_column)',
      `SELECT nope FROM r_users`, []],
    ['numeric overflow on total',
      `INSERT INTO r_orders (user_id, total) VALUES (1, 999999999999)`, []],
  ];
  for (const [label, text, params] of cases) {
    try {
      await q(text, params);
      console.log(`${label.padEnd(42)} → NO ERROR`);
    } catch (e) {
      console.log(`${label.padEnd(42)} → ${e.code}  ${e.constraint ?? ''}`);
      console.log(`${''.padEnd(42)}   message : ${e.message}`);
      console.log(`${''.padEnd(42)}   detail  : ${e.detail ?? '(none)'}`);
      console.log(`${''.padEnd(42)}   table/col: ${e.table ?? '-'} / ${e.column ?? '-'}`);
    }
  }
}

