// --- 6. the leak: a repo function that forgets release() -------------------
line('6. forgetting client.release() with max: 2');
{
  const small = new pg.Pool({
    connectionString: URL, max: 2, connectionTimeoutMillis: 1500});
  const stranded = [];               // script bookkeeping so we can clean up later
  const leaky = async () => {
    const c = await small.connect();
    stranded.push(c);
    await c.query('SELECT 1');
    // no release() — the client never goes back to the pool
  };
  await leaky();
  console.log('call 1: ok  (1 of 2 connections now held forever)');
  await leaky();
  console.log('call 2: ok  (2 of 2 held)');
  const t0 = Date.now();
  try {
    await leaky();
    console.log('call 3: ok — unexpected');
  } catch (e) {
    console.log(`call 3: ${e.message}  after ${Date.now() - t0} ms`);
  }
  console.log('pool counts →',
    `total=${small.totalCount} idle=${small.idleCount} waiting=${small.waitingCount}`);

  // and the second symptom: the process will not shut down either
  const ending = small.end();
  const verdict = await Promise.race([
    ending.then(() => 'resolved'),
    new Promise((r) => setTimeout(() => r('STILL PENDING after 2000 ms'), 2000)),
  ]);
  console.log('await pool.end() →', verdict);
  for (const c of stranded) c.release();
  await ending;
  console.log('after releasing the stranded clients, pool.end() → resolved');
}

// --- 7. the same three calls with release() in finally ---------------------
line('7. the same three calls, released in finally');
{
  const small = new pg.Pool({
    connectionString: URL, max: 2, connectionTimeoutMillis: 1500});
  const safe = async () => {
    const c = await small.connect();
    try {
      await c.query('SELECT 1');
    } finally {
      c.release();
    }
  };
  for (let i = 1; i <= 3; i++) {
    await safe();
    console.log(`call ${i}: ok`);
  }
  console.log('pool counts →',
    `total=${small.totalCount} idle=${small.idleCount} waiting=${small.waitingCount}`);
  await small.end();
}

// --- 8. release() does NOT undo session state -----------------------------
line('8. what survives release() back into the pool');
{
  const small = new pg.Pool({connectionString: URL, max: 1});
  const c1 = await small.connect();
  await c1.query(`SET statement_timeout = '3s'`);
  await c1.query(`CREATE TEMP TABLE r_leak (x int)`);
  c1.release();

  const c2 = await small.connect();   // max:1, so this is the same backend
  console.log('statement_timeout after release:',
    (await c2.query(`SHOW statement_timeout`)).rows[0].statement_timeout);
  console.log('temp table still visible:',
    (await c2.query(`SELECT to_regclass('pg_temp.r_leak') IS NOT NULL AS there`)).rows[0].there);
  c2.release();

  const c3 = await small.connect();
  c3.release(true);                   // destroy the connection instead of reusing
  const c4 = await small.connect();
  console.log('after release(true), statement_timeout:',
    (await c4.query(`SHOW statement_timeout`)).rows[0].statement_timeout);
  c4.release();
  await small.end();
}

await q(`DROP TABLE IF EXISTS r_orders, r_users CASCADE`);
await pool.end();
